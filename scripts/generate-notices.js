/**
 * Writes THIRD-PARTY-NOTICES.md: every production dependency in package-lock.json
 * with its version, SPDX licence and the full licence text shipped in node_modules.
 * Run after `npm install` whenever dependencies change:  npm run notices
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));

const LICENCE_FILE = /^(licen[cs]e|copying)([.-].*)?$/i;
const NOTICE_FILE = /^(third[-_ ]?party[-_ ]?notices?|notice)(\.[a-z]+)?$/i;

const seen = new Map();
for (const [key, meta] of Object.entries(lock.packages)) {
  if (!key || meta.dev) continue;
  const name = key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length);
  const id = `${name}@${meta.version}`;
  if (seen.has(id)) continue;
  const dir = path.join(root, key);
  let licenceText = '';
  let noticeText = '';
  if (fs.existsSync(dir)) {
    for (const f of fs.readdirSync(dir)) {
      const full = path.join(dir, f);
      if (!fs.statSync(full).isFile()) continue;
      if (LICENCE_FILE.test(f) && !licenceText) licenceText = fs.readFileSync(full, 'utf8').trim();
      else if (NOTICE_FILE.test(f)) noticeText = fs.readFileSync(full, 'utf8').trim();
    }
  }
  // Components vendored inside the package (e.g. node-pty's deps/winpty) with their own licence.
  const bundled = [];
  const depsDir = path.join(dir, 'deps');
  if (fs.existsSync(depsDir)) {
    for (const sub of fs.readdirSync(depsDir)) {
      const subDir = path.join(depsDir, sub);
      if (!fs.statSync(subDir).isDirectory()) continue;
      const lf = fs.readdirSync(subDir).find((f) => LICENCE_FILE.test(f));
      if (lf) bundled.push({ name: `deps/${sub}`, text: fs.readFileSync(path.join(subDir, lf), 'utf8').trim() });
    }
  }
  const licence = typeof meta.license === 'string' ? meta.license : 'UNSPECIFIED';
  seen.set(id, { name, version: meta.version, licence, licenceText, noticeText, bundled });
}

const entries = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const out = [];
out.push('# Third-party notices', '');
out.push('Drafting App is released under the MIT licence (see `LICENSE`). It is built on the open-source packages listed below, each under its own licence. Their copyright notices and licence texts are reproduced here so that packaged builds can carry them.', '');
out.push('Electron and Chromium are not listed individually: a packaged build already contains Electron\'s `LICENSE` and `LICENSES.chromium.html`, which must stay with the application.', '');
out.push('This file is generated by `npm run notices` from `package-lock.json` and the licence files in `node_modules`. Development-only tools are not included.', '');
out.push('## Summary', '', '| Package | Version | Licence |', '|---|---|---|');
for (const e of entries) out.push(`| ${e.name} | ${e.version} | ${e.licence} |`);
out.push('');
const missing = entries.filter((e) => !e.licenceText);
out.push('## Licence texts', '');
for (const e of entries) {
  out.push(`### ${e.name} ${e.version}`, '', `Licence: ${e.licence}`, '');
  if (e.licenceText) out.push('```text', e.licenceText, '```', '');
  else out.push(`_The package does not ship a licence file. It declares the licence \`${e.licence}\` in its package metadata._`, '');
  if (e.noticeText) out.push('Notices shipped with this package:', '', '```text', e.noticeText, '```', '');
  for (const b of e.bundled) out.push(`Bundled component \`${b.name}\`:`, '', '```text', b.text, '```', '');
}
fs.writeFileSync(path.join(root, 'THIRD-PARTY-NOTICES.md'), out.join('\n'), 'utf8');
console.log(`THIRD-PARTY-NOTICES.md: ${entries.length} packages, ${missing.length} without a licence file`);
if (missing.length) console.log('  without licence file: ' + missing.map((e) => e.name).join(', '));
